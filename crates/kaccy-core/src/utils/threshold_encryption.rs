//! Threshold Encryption for Orders
//!
//! Provides comprehensive threshold encryption support including:
//! - Time-based decryption keys
//! - Distributed key generation (DKG)
//! - Encrypted mempool for private transactions
//! - Fair transaction ordering via time-locked encryption
//!
//! # Secret sharing
//!
//! Distributed key generation relies on a real implementation of
//! [Shamir's Secret Sharing][shamir] (SSS) over the finite field
//! `GF(2^8)`. A secret is split into `N` shares with a recovery threshold
//! `T` such that:
//!
//! * **any** `T` shares reconstruct the secret exactly, and
//! * **any** `T - 1` shares reveal *nothing* about it
//!   (information-theoretic security).
//!
//! The arithmetic is byte-wise over `GF(2^8)` with the AES reducing
//! polynomial `0x11b`. Each byte of the secret is shared independently by a
//! random degree `T - 1` polynomial whose constant term is that secret byte
//! and whose higher coefficients come from a cryptographically secure RNG
//! ([`rand::rng`]). Shares are the polynomial evaluations at distinct,
//! non-zero `x`-coordinates; reconstruction is Lagrange interpolation
//! evaluated at `x = 0`.
//!
//! In addition, [`DKGSession::generate_shares`] derives a genuine
//! `secp256k1` public key `PK = secret * G` that binds the aggregated public
//! key to the shared secret (the secret is never revealed by `PK`).
//!
//! [shamir]: https://en.wikipedia.org/wiki/Shamir%27s_secret_sharing

use chrono::{DateTime, Utc};
use rand::{Rng, rng};
use secp256k1::{PublicKey, Secp256k1, SecretKey};
use serde::{Deserialize, Serialize};
