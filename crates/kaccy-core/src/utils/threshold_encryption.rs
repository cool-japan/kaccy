use crate::error::{CoreError, Result};

// ===========================================================================
// GF(2^8) finite-field arithmetic
// ===========================================================================

/// Precomputed exponential / logarithm tables for `GF(2^8)`.
///
/// The field is generated by the primitive element `0x03` modulo the AES
/// reducing polynomial `x^8 + x^4 + x^3 + x + 1` (`0x11b`). The tables let us
/// perform multiplication and inversion via table lookups instead of repeated
/// carry-less multiplication.
struct GfTables {
    /// `exp[i] == g^i` for `i in 0..510` (doubled to avoid `% 255` on lookup).
    exp: [u8; 512],
    /// `log[v]` is the discrete log of `v` base `g` (`log[0]` is unused).
    log: [u8; 256],
}

/// Build the `GF(2^8)` log/antilog tables once and cache them for the process.
fn gf_tables() -> &'static GfTables {
    static TABLES: OnceLock<GfTables> = OnceLock::new();
    TABLES.get_or_init(|| {
        let mut exp = [0u8; 512];
        let mut log = [0u8; 256];

        // Generator g = 0x03 is primitive for the polynomial 0x11b.
        let mut x: u16 = 1;
        for (i, exp_slot) in exp.iter_mut().enumerate().take(255) {
            *exp_slot = x as u8;
            log[x as usize] = i as u8;
            // Multiply by the generator (x * 3 == x ^ (x << 1)) in GF(2^8).
            x ^= x << 1;
            if x & 0x100 != 0 {
                x ^= 0x11b;
            }
            x &= 0xff;
        }
        // Duplicate the period-255 table into the tail so `exp[a + b]` never
        // needs a modulo. The largest index ever used is
        // log(a) + log(b) <= 254 + 254 == 508. Borrow the first 255 entries
        // immutably while filling the remainder.
        let (low, high) = exp.split_at_mut(255);
        for (j, slot) in high.iter_mut().enumerate() {
            *slot = low[j % 255];
        }

        GfTables { exp, log }
    })
}

/// Multiply two `GF(2^8)` elements.
#[inline]
fn gf_mul(a: u8, b: u8) -> u8 {
    if a == 0 || b == 0 {
        return 0;
    }
    let t = gf_tables();
    let log_sum = t.log[a as usize] as usize + t.log[b as usize] as usize;
    t.exp[log_sum]
}

/// Multiplicative inverse of a non-zero `GF(2^8)` element.
///
/// Returns `None` for `0`, which has no inverse.
#[inline]
fn gf_inv(a: u8) -> Option<u8> {
    if a == 0 {
        return None;
    }
    let t = gf_tables();
    // a^-1 = g^(255 - log(a)).
    Some(t.exp[255 - t.log[a as usize] as usize])
}

/// Divide `a` by `b` in `GF(2^8)`.
#[inline]
fn gf_div(a: u8, b: u8) -> Option<u8> {
    gf_inv(b).map(|inv| gf_mul(a, inv))
}

/// Evaluate a `GF(2^8)` polynomial (constant term first) at point `x` using
/// Horner's method.
#[inline]
fn gf_poly_eval(coeffs: &[u8], x: u8) -> u8 {
    let mut acc = 0u8;
    for &c in coeffs.iter().rev() {
        // acc = acc * x + c    (addition in GF(2^8) is XOR)
        acc = gf_mul(acc, x) ^ c;
    }
    acc
}

// ===========================================================================
// Shamir's Secret Sharing over GF(2^8)
// ===========================================================================

/// Maximum number of distinct, non-zero `x`-coordinates available in
/// `GF(2^8)`. With `x in 1..=255` we can host at most 255 shares.
pub const MAX_SHAMIR_SHARES: u32 = 255;

/// A single Shamir share: a distinct non-zero `x`-coordinate together with the
/// per-byte `y`-evaluations of the secret polynomials.
///
/// `y` has the same length as the original secret; `y[k]` is the evaluation of
/// the `k`-th byte's polynomial at `x`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShamirShare {
    /// Evaluation point (`1..=255`, never zero).
    pub x: u8,
    /// Per-byte polynomial evaluations at `x`.
    pub y: Vec<u8>,
}

/// Split `secret` into `total` Shamir shares with recovery threshold
/// `threshold` over `GF(2^8)`.
///
/// Coefficients above the constant term are drawn from a cryptographically
/// secure RNG, so any `threshold - 1` shares are information-theoretically
/// independent of the secret. An empty secret is permitted and yields shares
/// with empty `y` vectors (still carrying valid distinct `x`-coordinates).
///
/// # Errors
///
/// Returns [`CoreError::Validation`] when `threshold == 0`,
/// `threshold > total`, or `total` exceeds [`MAX_SHAMIR_SHARES`].
pub fn shamir_split_secret(
    secret: &[u8],
    threshold: u32,
    total: u32,
) -> Result<Vec<ShamirShare>> {
    if threshold == 0 {
        return Err(CoreError::Validation(
            "Shamir threshold must be at least 1".to_string(),
        ));
    }
    if threshold > total {
        return Err(CoreError::Validation(format!(
            "Shamir threshold ({threshold}) cannot exceed total shares ({total})"
        )));
    }
    if total > MAX_SHAMIR_SHARES {
        return Err(CoreError::Validation(format!(
            "Shamir total shares ({total}) cannot exceed {MAX_SHAMIR_SHARES}"
        )));
    }

    let degree = (threshold - 1) as usize;
    let mut csprng = rng();

    // For each secret byte, build a random polynomial whose constant term is
    // the secret byte. coefficients[k] has length `threshold` (degree+1).
    let mut polynomials: Vec<Vec<u8>> = Vec::with_capacity(secret.len());
    for &secret_byte in secret {
        let mut coeffs = vec![0u8; degree + 1];
        coeffs[0] = secret_byte;
        if degree > 0 {
            // Fill the higher-order coefficients with CSPRNG bytes.
            csprng.fill_bytes(&mut coeffs[1..]);
        }
        polynomials.push(coeffs);
    }

    // Evaluate every polynomial at x = 1, 2, ..., total.
    let mut shares = Vec::with_capacity(total as usize);
    for i in 0..total {
        // x must be non-zero; map share i -> x = i + 1 (fits in u8 since
        // total <= 255).
        let x = (i + 1) as u8;
        let y: Vec<u8> = polynomials.iter().map(|p| gf_poly_eval(p, x)).collect();
        shares.push(ShamirShare { x, y });
    }

    Ok(shares)
}

/// Reconstruct a secret from at least `threshold` Shamir shares produced by
/// [`shamir_split_secret`].
///
/// Reconstruction performs Lagrange interpolation in `GF(2^8)` evaluated at
/// `x = 0`, independently for each byte position. Supplying more than the
/// threshold number of shares is fine; supplying fewer simply yields a
/// different (and, by the security of SSS, unrelated) value.
///
/// # Errors
///
/// Returns [`CoreError::Validation`] when no shares are supplied, when shares
/// disagree on the secret length, when an `x`-coordinate is zero, or when two
/// shares share the same `x`-coordinate (which would make interpolation
/// singular).
pub fn shamir_reconstruct_secret(shares: &[ShamirShare]) -> Result<Vec<u8>> {
    if shares.is_empty() {
        return Err(CoreError::Validation(
            "Cannot reconstruct secret from zero shares".to_string(),
        ));
    }

    let secret_len = shares[0].y.len();
    for share in shares {
        if share.x == 0 {
            return Err(CoreError::Validation(
                "Shamir share x-coordinate must be non-zero".to_string(),
            ));
        }
        if share.y.len() != secret_len {
            return Err(CoreError::Validation(
                "Shamir shares disagree on secret length".to_string(),
            ));
        }
    }

    // Reject duplicate x-coordinates: Lagrange interpolation divides by
    // (x_i - x_j); equal coordinates make that term singular.
    for (i, a) in shares.iter().enumerate() {
        for b in &shares[i + 1..] {
            if a.x == b.x {
                return Err(CoreError::Validation(format!(
                    "Duplicate Shamir share x-coordinate: {}",
                    a.x
                )));
            }
        }
    }

    // Empty secrets reconstruct to an empty vector (and the x-coordinates were
    // already validated above).
    if secret_len == 0 {
        return Ok(Vec::new());
    }

    let mut secret = vec![0u8; secret_len];

    // Precompute the Lagrange basis coefficients L_i(0) once; they do not
    // depend on the byte position.
    //
    //   L_i(0) = prod_{j != i} (0 - x_j) / (x_i - x_j)
    //          = prod_{j != i} x_j / (x_i ^ x_j)   in GF(2^8)
    //
    // (subtraction == addition == XOR over GF(2^8)).
    let mut basis = Vec::with_capacity(shares.len());
    for (i, share_i) in shares.iter().enumerate() {
        let mut numerator = 1u8;
        let mut denominator = 1u8;
        for (j, share_j) in shares.iter().enumerate() {
            if i == j {
                continue;
            }
            numerator = gf_mul(numerator, share_j.x);
            denominator = gf_mul(denominator, share_i.x ^ share_j.x);
        }
        let coeff = gf_div(numerator, denominator).ok_or_else(|| {
            CoreError::Calculation(
                "Singular Lagrange interpolation (duplicate x-coordinate)".to_string(),
            )
        })?;
        basis.push(coeff);
    }

    // secret[k] = XOR_i ( y_i[k] * L_i(0) ).
    for (share, &coeff) in shares.iter().zip(basis.iter()) {
        for (acc, &y) in secret.iter_mut().zip(share.y.iter()) {
            *acc ^= gf_mul(y, coeff);
        }
    }

    Ok(secret)
}

// ===========================================================================
// secp256k1 public-key binding for the shared secret
// ===========================================================================

/// Derive the aggregated public key `PK = secret * G` on the `secp256k1`
/// curve, binding the public key to the shared secret without revealing it.
///
/// The 32-byte master secret is interpreted as a big-endian scalar. To make
/// every random secret usable as a curve scalar (a uniformly random 32-byte
/// value can be `0` or `>= n` with negligible probability), the secret is
/// hashed into the valid scalar range via rejection-style folding before the
/// scalar multiplication. The returned bytes are the 33-byte compressed
/// SEC1 encoding of `PK`.
fn derive_public_key(master_secret: &[u8]) -> Result<Vec<u8>> {
    let secp = Secp256k1::new();
    let secret_key = secret_key_from_bytes(master_secret)?;
    let public_key = PublicKey::from_secret_key(&secp, &secret_key);
    Ok(public_key.serialize().to_vec())
}

/// Map arbitrary bytes to a valid `secp256k1` [`SecretKey`].
///
/// We hash the input into 32 bytes and, in the astronomically unlikely event
/// that the result is not a valid scalar (zero or `>= n`), re-hash with a
/// counter until a valid scalar is found. This terminates with overwhelming
/// probability after a single iteration.
fn secret_key_from_bytes(bytes: &[u8]) -> Result<SecretKey> {
    let mut counter: u32 = 0;
    loop {
        let mut hasher = Sha256::new();
        hasher.update(b"kaccy-threshold-secret-key-v1");
        hasher.update(counter.to_le_bytes());
        hasher.update(bytes);
        let digest: [u8; 32] = hasher.finalize().into();

        match SecretKey::from_byte_array(digest) {
            Ok(secret_key) => return Ok(secret_key),
            Err(_) => {
                // Extremely unlikely; advance the counter and retry. Bound the
                // loop defensively so we never spin forever.
                counter = counter.checked_add(1).ok_or_else(|| {
                    CoreError::Calculation(
                        "Failed to derive a valid secp256k1 secret key".to_string(),
                    )
                })?;
                if counter > 1024 {
                    return Err(CoreError::Calculation(
                        "Failed to derive a valid secp256k1 secret key".to_string(),
                    ));
                }
            }
        }
    }
}

